def test_network_info_over_the_wire(client: TestClient) -> None:
    ws = _authenticated(client)
    request = Envelope(type=MessageType.NETWORK_INFO, payload=NetworkInfoPayload())
    ws.send_json(request.model_dump(mode="json"))

    reply = ws.receive_json()
    assert reply["type"] == MessageType.NETWORK_INFO_RESULT.value
    assert reply["id"] == request.id
    assert reply["payload"]["hostname"]
    assert reply["payload"]["interfaces"]
